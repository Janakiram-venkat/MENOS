"""Shared fixtures for the menos.pennylane tests (docs/adr/0024 section 5).

The random circuits are tests/ir/fixtures/random_circuits.json (generated by
tools/gen_fixtures.py with Qiskit oracles), rebuilt as PennyLane operations.
Qubit j of a fixture is wire j.
"""

from __future__ import annotations

import json
import pathlib

import numpy as np
import pennylane as qml

FIXTURE_PATH = pathlib.Path(__file__).resolve().parents[2] / "tests/ir/fixtures/random_circuits.json"

TOL = 1e-12  # src/common/tolerance.h kDefaultAbsTol; docs/adr/0024 Q11


def load_fixtures() -> list[dict]:
    return json.loads(FIXTURE_PATH.read_text())["circuits"]


def _gate(name, params, wires):
    simple = {
        "x": qml.PauliX,
        "y": qml.PauliY,
        "z": qml.PauliZ,
        "h": qml.Hadamard,
        "s": qml.S,
        "t": qml.T,
        "sx": qml.SX,
        "cx": qml.CNOT,
        "cz": qml.CZ,
        "swap": qml.SWAP,
        "ccx": qml.Toffoli,
    }
    if name in simple:
        return simple[name](wires=wires)
    if name in ("sdg", "tdg", "sxdg"):
        return qml.adjoint({"sdg": qml.S, "tdg": qml.T, "sxdg": qml.SX}[name](wires=wires))
    if name in ("rx", "ry", "rz"):
        return {"rx": qml.RX, "ry": qml.RY, "rz": qml.RZ}[name](params[0], wires=wires)
    if name == "p":
        return qml.PhaseShift(params[0], wires=wires)
    if name == "cp":
        return qml.ControlledPhaseShift(params[0], wires=wires)
    if name == "u":
        # Qiskit's UGate(theta, phi, lambda) is PennyLane's U3(theta, phi, delta).
        return qml.U3(*params, wires=wires)
    raise ValueError(name)


def fixture_operations(entry: dict) -> list:
    """The fixture as PennyLane operations, global phase included."""
    ops = []
    for op in entry["operations"]:
        if op["opcode"] == "unitary":
            matrix = np.asarray(op["matrix_real"]) + 1j * np.asarray(op["matrix_imag"])
            # Qiskit's matrix is little-endian in its qubit list; PennyLane's
            # is big-endian in its wires, so the wires are reversed.
            ops.append(qml.QubitUnitary(matrix, wires=op["qubits"][::-1]))
        else:
            ops.append(_gate(op["opcode"], op["params"], op["qubits"]))
    # Qiskit multiplies by e^{+i phase}; PennyLane's GlobalPhase by e^{-i phi}.
    ops.append(qml.GlobalPhase(-entry["global_phase"], wires=range(entry["num_qubits"])))
    return ops


def fixture_statevector_big_endian(entry: dict) -> np.ndarray:
    state = np.asarray(entry["expected_statevector_real"]) + 1j * np.asarray(
        entry["expected_statevector_imag"]
    )
    n = entry["num_qubits"]
    return state.reshape([2] * n).transpose(range(n - 1, -1, -1)).reshape(-1)


def fixture_observable(entry: dict):
    """The fixture's Pauli-sum observable as a PennyLane operator."""
    terms = []
    for term in entry["observable"]["terms"]:
        xs, zs = set(term["x_qubits"]), set(term["z_qubits"])
        factors = []
        for q in sorted(xs | zs):
            if q in xs and q in zs:
                factors.append(qml.Y(q))
            elif q in xs:
                factors.append(qml.X(q))
            else:
                factors.append(qml.Z(q))
        if not factors:
            word = qml.Identity(0)
        elif len(factors) == 1:
            word = factors[0]
        else:
            word = qml.prod(*factors)
        terms.append(qml.s_prod(term["coeff_real"], word))
    return qml.sum(*terms) if len(terms) > 1 else terms[0]


def run_both(device_a, device_b, ops, measurements, *, shots=None):
    tape = qml.tape.QuantumScript(ops, measurements, shots=shots)
    return qml.execute([tape], device_a)[0], qml.execute([tape], device_b)[0]
